import { execFileSync } from 'node:child_process';
import { appendFileSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';

const repository = 'Seungwoo321/seungwoo321.github.io';
const site = 'https://seungwoo321.github.io';
export function calendarFile(revision) {
  validatePlan({ revision, futureDates:[] });
  return `.github/workflows/publish-scheduled-${revision}.yml`;
}
const calendarApi = revision => `repos/${repository}/actions/workflows/${calendarFile(revision).split('/').at(-1)}`;
const command = (bin, args) => execFileSync(bin, args, { encoding:'utf8', stdio:['ignore','pipe','pipe'] }).trim();
const gh = (...args) => command('gh', args);
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
export function validatePlan(plan) {
  if (!plan || !/^[a-f0-9]{40}$/.test(plan.revision || '') || !Array.isArray(plan.futureDates) || plan.futureDates.some(date => typeof date !== 'string' || !Number.isFinite(Date.parse(date)))) throw new Error('Invalid published release plan');
  return { revision:plan.revision, futureDates:[...new Set(plan.futureDates)].sort((a,b)=>Date.parse(a)-Date.parse(b)) };
}
export function cronDates(dates) {
  return [...new Set(dates.map(value => {
    const time=Date.parse(value); if (!Number.isFinite(time)) throw new Error('Invalid publication date');
    const date=new Date(Math.ceil(time/60000)*60000);
    return `${date.getUTCMinutes()} ${date.getUTCHours()} ${date.getUTCDate()} ${date.getUTCMonth()+1} *`;
  }))];
}
export function releaseDecision(plan, revision, now=Date.now()) {
  validatePlan(plan);
  return { publish:plan.revision===revision && plan.futureDates.some(date=>Date.parse(date)<=now), finished:plan.revision===revision && plan.futureDates.length===0 };
}
export function calendarWorkflow(plan) {
  validatePlan(plan);
  if (!plan.futureDates.length) throw new Error('No scheduled posts');
  return `# Generated by npm run schedule. Times are UTC; this workflow disables itself after its final release.
# source-revision: ${plan.revision}
name: Publish scheduled posts
on:
  workflow_dispatch:
  schedule:
${cronDates(plan.futureDates).map(cron=>`    - cron: '${cron}'`).join('\n')}
permissions:
  contents: read
jobs:
  release:
    permissions:
      contents: read
      pages: write
      id-token: write
      actions: read
    uses: ${repository}/.github/workflows/astro-pages.yml@${plan.revision}
    with:
      revision: '${plan.revision}'
      scheduled: true
  finish:
    needs: release
    if: >-
      needs.release.outputs.finished == 'true' ||
      (needs.release.outputs.deployment_result == 'success' && needs.release.outputs.upcoming_count == '0')
    runs-on: ubuntu-latest
    permissions:
      contents: read
      actions: write
    steps:
      - uses: actions/checkout@v7
        with:
          ref: '${plan.revision}'
      - uses: actions/setup-node@v7
        with:
          node-version: 24
      - run: node scripts/publication.mjs finish
        env:
          GH_TOKEN: \${{ github.token }}
          PUBLICATION_REVISION: '${plan.revision}'
`;
}
function output(values) {
  if (!process.env.GITHUB_OUTPUT) throw new Error('Missing GitHub Actions output file');
  appendFileSync(process.env.GITHUB_OUTPUT,Object.entries(values).map(([key,value])=>`${key}=${value}`).join('\n')+'\n');
}
async function livePlan() {
  const response=await fetch(`${site}/.well-known/publication.json?check=${Date.now()}`,{headers:{'Cache-Control':'no-cache'},signal:AbortSignal.timeout(20000)});
  if (!response.ok) throw new Error(`Published release plan returned HTTP ${response.status}`);
  return validatePlan(await response.json());
}
function cleanMain() {
  if (command('git',['branch','--show-current'])!=='main') throw new Error('Use the main worktree');
  if (command('git',['status','--porcelain'])) throw new Error('Commit and push your changes before deploying or scheduling');
  if (gh('repo','view','--json','nameWithOwner','--jq','.nameWithOwner')!==repository) throw new Error('Unexpected repository');
  const revision=command('git',['rev-parse','HEAD']);
  const remote=command('git',['ls-remote','origin','refs/heads/main']).split(/\s/)[0];
  if (remote!==revision) throw new Error('Local main and origin/main differ; synchronize them first');
  return revision;
}
function calendarExists(revision) {
  try { gh('api',calendarApi(revision)); return true; }
  catch(error) { if (String(error.stderr).includes('404')) return false; throw error; }
}
function disableCalendar(revision) { if (calendarExists(revision)) gh('api','--method','PUT',calendarApi(revision)+'/disable'); }
function disablePreviousCalendars(revision) {
  const pages=JSON.parse(gh('api','--paginate','--slurp',`repos/${repository}/actions/workflows?per_page=100`));
  for(const workflow of pages.flatMap(page=>page.workflows)) {
    if(/^\.github\/workflows\/publish-scheduled(?:-[a-f0-9]{40})?\.yml$/.test(workflow.path) && workflow.path!== (revision ? calendarFile(revision) : '') && workflow.state==='active') {
      gh('api','--method','PUT',`repos/${repository}/actions/workflows/${workflow.id}/disable`);
    }
  }
}
async function deployRevision(revision) {
  const before=JSON.parse(gh('run','list','--repo',repository,'--workflow','astro-pages.yml','--branch','main','--event','workflow_dispatch','--limit','10','--json','databaseId'));
  gh('workflow','run','astro-pages.yml','--repo',repository,'--ref','main','-f',`revision=${revision}`);
  const deadline=Date.now()+60000; let id;
  while(Date.now()<deadline) {
    const runs=JSON.parse(gh('run','list','--repo',repository,'--workflow','astro-pages.yml','--branch','main','--event','workflow_dispatch','--limit','10','--json','databaseId,displayTitle'));
    id=runs.find(run=>run.displayTitle.includes(revision) && !before.some(old=>old.databaseId===run.databaseId))?.databaseId;
    if(id) break; await sleep(2000);
  }
  if(!id) throw new Error('Dispatch submitted; run not yet visible. Check Actions before retrying deployment');
  console.log(`Deployment: https://github.com/${repository}/actions/runs/${id}`);
  execFileSync('gh',['run','watch',String(id),'--repo',repository,'--exit-status','--interval','5'],{stdio:'inherit'});
  const planDeadline=Date.now()+90000;
  while(Date.now()<planDeadline) {
    try { const plan=await livePlan();if(plan.revision===revision)return plan; } catch(error) { console.log(error.message); }
    await sleep(5000);
  }
  throw new Error('Deployment succeeded but public metadata is not current yet. Retry npm run schedule after propagation');
}
async function schedule(plan) {
  const calendarBase=cleanMain();
  disablePreviousCalendars(plan.futureDates.length ? plan.revision : undefined);
  if(!plan.futureDates.length) { console.log('No future posts. No scheduled executions are active.');return; }
  if(plan.futureDates.some(date=>Date.parse(date)<=Date.now())) throw new Error('A post became due during deployment. Run npm run deploy to release it before registering new times');
  const yaml=calendarWorkflow(plan);
  const file=calendarFile(plan.revision);
  if(!existsSync(file)||readFileSync(file,'utf8')!==yaml) {
    writeFileSync(file,yaml);
    command('git',['add','--',file]);
    command('git',['commit','-m','chore: schedule approved post publications','--',file]);
    const calendarRevision=command('git',['rev-parse','HEAD']);
    if(command('git',['rev-parse','HEAD^'])!==calendarBase)throw new Error('Main changed concurrently; calendar was not pushed');
    execFileSync('git',['push','origin',`${calendarRevision}:refs/heads/main`],{stdio:'inherit'});
  }
  const deadline=Date.now()+60000;
  while(!calendarExists(plan.revision)) { if(Date.now()>deadline)throw new Error('Calendar committed; workflow registration is pending. Retry npm run schedule');await sleep(2000); }
  gh('api','--method','PUT',calendarApi(plan.revision)+'/enable');
  if(plan.futureDates.some(date=>Date.parse(date)<=Date.now())) {
    disableCalendar(plan.revision);
    throw new Error('A post became due while registering the calendar. Run npm run deploy to release it');
  }
  console.log(`Scheduled ${plan.futureDates.length} publication time(s):\n${plan.futureDates.join('\n')}`);
}
export async function main(mode) {
  if(mode==='gate') {
    let decision={publish:true,finished:false};
    if(process.env.SCHEDULED_RELEASE==='true') {
      const runs=JSON.parse(gh('run','list','--repo',repository,'--workflow','astro-pages.yml','--branch','main','--event','workflow_dispatch','--status','success','--limit','1','--json','displayTitle'));
      const approved=runs[0]?.displayTitle.match(/^Deploy Astro ([a-f0-9]{40})$/)?.[1];
      decision=approved===process.env.PUBLICATION_REVISION ? releaseDecision(await livePlan(),approved) : {publish:false,finished:false};
    }
    output(decision);return;
  }
  if(mode==='outputs') {
    const plan=validatePlan(JSON.parse(readFileSync('dist/.well-known/publication.json','utf8')));
    output({upcoming_count:plan.futureDates.length});return;
  }
  if(mode==='finish') {
    disableCalendar(process.env.PUBLICATION_REVISION);
    return;
  }
  if(mode!=='deploy'&&mode!=='schedule')throw new Error('Use npm run deploy or npm run schedule');
  mkdirSync('.local',{recursive:true});const lock='.local/publication-lock';
  try { mkdirSync(lock); } catch(error) { if(error.code==='EEXIST')throw new Error('Another publication command is active (.local/publication-lock)');throw error; }
  try {
    const revision=cleanMain();
    if(mode==='schedule') { await schedule(await livePlan());return; }
    let plan=await deployRevision(revision);
    // Catch a publication time that elapsed while the first build was being deployed.
    if(plan.futureDates.some(date=>Date.parse(date)<=Date.now()))plan=await deployRevision(revision);
    await schedule(plan);
  } finally { rmSync(lock,{recursive:true}); }
}
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href)main(process.argv[2]).catch(error=>{console.error(error.message);process.exitCode=1;});
